"""Generate report numbers and readable result notes from raw experiment files."""
import json
import shutil
from .experiments import ROOT
from .plots import read


def main():
    results, report = ROOT / "results", ROOT / "report"
    report.mkdir(exist_ok=True)
    (report / "figures").mkdir(exist_ok=True)
    for name in ("main_results.pdf", "policy_stress.pdf"):
        shutil.copy2(results / "figures" / name, report / "figures" / name)
    rows = {r["policy"]: r for r in read(results / "summary.csv")}
    pairs = {r["opponent"]: r for r in read(results / "paired_summary.csv")}
    meta = json.loads((results / "manifest.json").read_text())
    q = float(rows["Q-learning"]["return"])
    greedy = float(rows["Greedy immediate"]["return"])
    optimum = meta["exact_optimal_expected_start_return"]
    commands = {"QReturn": q, "QCI": float(rows["Q-learning"]["return_ci95"]),
                "GreedyReturn": greedy, "GainPercent": 100 * (q / greedy - 1),
                "OptPercent": 100 * q / optimum, "OptValue": optimum, "GapValue": optimum - q,
                "PairedGain": float(pairs["Greedy immediate"]["gain"]), "PairedCI": float(pairs["Greedy immediate"]["ci95"]),
                "FatigueGain": float(pairs["Q without fatigue"]["gain"]), "FatigueCI": float(pairs["Q without fatigue"]["ci95"])}
    text = "% Generated by python -m privacyguard.report_assets; do not type experimental numbers here.\n"
    for name, value in commands.items():
        text += f"\\newcommand{{\\{name}}}{{{value:.2f}}}\n"
    selected = [("Q-learning", "Q-learning"), ("SARSA", "SARSA"), ("Myopic Q", "Myopic Q (gamma=0)"),
                ("No budget obs.", "Q without budget"), ("No fatigue obs.", "Q without fatigue"),
                ("Greedy", "Greedy immediate"), ("Always coarse", "Always coarse"), ("Exact DP", "Exact DP ceiling")]
    table = ""
    for label, key in selected:
        row = rows[key]
        table += (f"{label} & ${float(row['return']):.2f}\\pm{float(row['return_ci95']):.2f}$"
                  f" & {float(row['utility']):.2f} & {float(row['exposure']):.2f} " + "\\\\\n")
    text += "\\newcommand{\\ResultsRows}{%\n" + table + "}\n"
    (report / "generated_metrics.tex").write_text(text, encoding="utf-8")
    lines = ["# Measured results", "", "All numbers below were generated from the saved experiment CSVs.", "",
             f"**Q-learning improves session return by {100*(q/greedy-1):.2f}% over greedy immediate sharing and reaches {100*q/optimum:.2f}% of the exact model optimum.**", "",
             "| Policy | Return ± 95% t CI | Utility | Exposure | Prompts |", "|---|---:|---:|---:|---:|"]
    for label, key in selected:
        row = rows[key]
        lines.append(f"| {label} | {float(row['return']):.3f} ± {float(row['return_ci95']):.3f} | {float(row['utility']):.3f} | {float(row['exposure']):.3f} | {float(row['prompts']):.3f} |")
    lines.extend(["", f"Exact expected optimum: {optimum:.6f}. Its sampled test return differs due to Monte Carlo noise. The learned-return gap estimated against that ceiling is {optimum-q:.3f}.", "",
                  "## Paired comparisons", "", "Positive values favour full Q-learning. Intervals use eight independent seed means.", "",
                  "| Opponent | Paired return gain ± 95% t CI |", "|---|---:|---:|"])
    for key, row in pairs.items():
        lines.append(f"| {key} | {float(row['gain']):.3f} ± {float(row['ci95']):.3f} |")
    lines.extend(["", "The fatigue-observation advantage is small and its paired interval includes zero. This experiment does not establish a reliable benefit from observing fatigue under the nominal parameters. Budget observation and future planning have much larger measured effects.", "",
                  "## Stress tests", "", "Q-learning is frozen; greedy knows the shifted immediate reward parameters. These are simulation stress tests, not evidence of generalisation to real users.", "",
                  "| Condition | Frozen Q return | Greedy return |", "|---|---:|---:|"])
    from .experiments import ci
    import numpy as np
    stress = read(results / "robustness.csv")
    for condition in dict.fromkeys(r["condition"] for r in stress):
        values = [[float(r["return"]) for r in stress if r["condition"] == condition and r["policy"] == label] for label in ("Q-learning", "Greedy immediate")]
        lines.append(f"| {condition} | {np.mean(values[0]):.3f} ± {ci(values[0]):.3f} | {np.mean(values[1]):.3f} ± {ci(values[1]):.3f} |")
    lines.extend(["", "## Protocol", "", f"Eight seeds × five variants × {meta['arguments']['episodes']:,} training episodes = {8*5*meta['arguments']['episodes']:,} simulated training episodes (including shortened exploring-start episodes). Each policy has 5,000 held-out sessions per seed. Final checkpoints, no test-based selection. Saved demo agent: seed 0.", "",
                  f"Training/evaluation wall time on the execution machine: {meta['total_wall_seconds']:.1f} seconds, excluding plotting. All seed-level metrics, action fractions, checkpoint hashes, and validation curves are retained in results/.", "",
                  "## Interpretation", "", "The agent allocates scarce exposure toward valuable requests rather than maximising immediate task benefit. It delivers higher measured utility while using less exposure than the greedy reference. This is an internal benchmark result under the declared synthetic cost model. It does not validate the cost weights, prove privacy, or guarantee a course grade."])
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Updated self-contained report assets and docs/RESULTS.md")


if __name__ == "__main__":
    main()
